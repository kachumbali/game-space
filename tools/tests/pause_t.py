# v0.2.2 pause menu: Esc opens it, RESUME / RESTART / OPTIONS / EXIT (confirm), Gauntlet banks the score, mouse is not re-captured while paused, no firing while paused.
from lib import *
import os
os.makedirs('/tmp/gs_shots', exist_ok=True)
ok = True
def check(name, cond, info=''):
    global ok
    print(('PASS ' if cond else 'FAIL ') + name, info)
    ok = ok and bool(cond)
VIS = "(id)=>getComputedStyle(document.getElementById(id)).display"
SPY = "()=>{window.__lockCalls=0;const c=document.getElementById('c');c.requestPointerLock=()=>{window.__lockCalls++;return Promise.resolve()}}"
with Runner() as R:
    # --- free flight: Esc, buttons, no firing, no mouse capture while paused, resume
    pg = R.page(1280, 720, '?free&go&q=low'); pg.wait_for_timeout(1500)
    pg.evaluate(SPY)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(300)
    r = pg.evaluate("()=>({paused:__game.userPause,ov:getComputedStyle(document.getElementById('pauseOv')).display,btns:[...document.querySelectorAll('#pauseOv button')].map(b=>b.textContent.replace(/\\s+/g,' ').trim()),sub:document.getElementById('pm_sub').textContent})")
    print(' ', r)
    check('Esc opens the pause menu with 4 buttons', r['paused'] and r['ov'] == 'block' and len(r['btns']) == 4 and r['btns'][0].startswith('RESUME') and 'MAIN MENU' in r['btns'][3], r['btns'])
    pg.screenshot(path='/tmp/gs_shots/pause_desk.png')
    m0 = pg.evaluate("()=>__game.missiles.length")
    pg.keyboard.press('Space'); pg.keyboard.press('KeyZ'); pg.wait_for_timeout(200)
    pg.keyboard.press('Space'); pg.keyboard.press('KeyZ'); pg.wait_for_timeout(200)
    chk = pg.evaluate("()=>[__game.missiles.length,__game.userPause]"); check('Space and Z do nothing while paused (no shots, no flares)', chk == [m0, True], (chk, m0))
    pg.keyboard.press('Enter'); pg.wait_for_timeout(200)
    check('Enter with nothing focused presses RESUME (not a missile launch)', pg.evaluate("()=>[__game.missiles.length,__game.userPause]") == [m0, False])
    pg.evaluate("()=>{__game.pauseToggle(true);window.__lockCalls=0}")
    pg.click('#pm_opt'); pg.wait_for_timeout(300)
    check('OPTIONS button opens the options panel', pg.evaluate(VIS, 'opts') == 'flex')
    check('clicking a pause button does not re-capture the mouse', pg.evaluate("()=>window.__lockCalls") == 0, pg.evaluate("()=>window.__lockCalls"))
    pg.keyboard.press('KeyO'); pg.wait_for_timeout(300)
    check('closing options keeps the pause menu and does not lock the mouse', pg.evaluate("()=>[__game.userPause,window.__lockCalls]") == [True, 0], pg.evaluate("()=>[__game.userPause,window.__lockCalls]"))
    pg.click('#pm_rst'); pg.wait_for_timeout(300)
    check('RESTART opens the restart dialog', pg.evaluate(VIS, 'rdlg') == 'flex')
    pg.click('#rd0'); pg.wait_for_timeout(200)
    pg.click('#pm_res'); pg.wait_for_timeout(300)
    check('RESUME resumes and asks for the mouse', pg.evaluate("()=>[__game.userPause,window.__lockCalls>=1]") == [False, True])
    pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    check('Esc pauses again, Esc resumes', pg.evaluate("()=>__game.userPause") is True)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    check('Esc resumes', pg.evaluate("()=>__game.userPause") is False)
    # losing the mouse lock in flight opens the pause menu (simulated)
    pg.evaluate("()=>{const c=document.getElementById('c');Object.defineProperty(document,'pointerLockElement',{configurable:true,get:()=>window.__lockOn?c:null});window.__lockOn=true;document.dispatchEvent(new Event('pointerlockchange'));window.__lockOn=false;document.dispatchEvent(new Event('pointerlockchange'))}")
    check('losing the mouse lock pauses', pg.evaluate("()=>__game.userPause") is True)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(100)
    check('an Esc right after an automatic pause is ignored (it is the same key press)', pg.evaluate("()=>__game.userPause") is True)
    pg.wait_for_timeout(400); pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    check('a later Esc resumes', pg.evaluate("()=>__game.userPause") is False)
    # EXIT in free flight: two clicks (confirm), back to the main menu
    pg.evaluate("()=>__game.pauseToggle(true)"); pg.wait_for_timeout(200)
    pg.click('#pm_exit'); pg.wait_for_timeout(200)
    r = pg.evaluate("()=>[document.getElementById('pm_exit').textContent,__game.userPause,document.getElementById('brief').style.display]")
    check('first EXIT click only arms (asks to confirm), nothing is lost yet', r[0].startswith('CONFIRM') and r[1] is True and r[2] != 'flex', r)
    pg.screenshot(path='/tmp/gs_shots/pause_confirm.png')
    pg.click('#pm_exit'); pg.wait_for_timeout(2500)
    r = pg.evaluate("()=>({paused:__game.userPause,brief:getComputedStyle(document.getElementById('brief')).display,has:document.getElementById('brief').textContent.includes('CAMPAIGN')})")
    check('second click returns to the main menu', not r['paused'] and r['brief'] == 'flex' and r['has'], r)
    pg.close()
    # --- mission: EXIT MISSION restores the crew and shows the menu
    pg = R.page(1280, 720, '?go&m=1&q=low'); pg.wait_for_function("()=>__game.state==='play'", timeout=60000); pg.wait_for_timeout(800)
    pg.evaluate("()=>{__game.game.crewSnap=JSON.stringify(__game.CREW);__game.CREW.hawk.status='KIA'}")
    pg.keyboard.press('Escape'); pg.wait_for_timeout(300)
    _t=pg.evaluate("()=>[document.getElementById('pm_exit').textContent,document.getElementById('pm_sub').textContent]"); check('mission pause shows EXIT MISSION and the title', 'EXIT MISSION' in pg.evaluate("()=>document.getElementById('pm_exit').textContent") and 'LILYPAD' in pg.evaluate("()=>document.getElementById('pm_sub').textContent"), _t)
    pg.click('#pm_exit'); pg.click('#pm_exit'); pg.wait_for_timeout(2500)
    r = pg.evaluate("()=>({menu:document.getElementById('brief').textContent.includes('CAMPAIGN'),hawk:JSON.parse(localStorage.getItem('gs_crew')).hawk.status})")
    check('EXIT MISSION goes to the main menu and the abandoned sortie costs the wing nothing', r['menu'] and r['hawk'] != 'KIA', r)
    pg.close()
    # --- Gauntlet: END RUN banks the score and shows the debrief
    pg = R.page(1280, 720, '?sv=1&sv_seed=5&q=low'); pg.wait_for_timeout(1500)
    pg.evaluate("()=>{const g=__game;g.juice.score=1234;}")
    pg.keyboard.press('Escape'); pg.wait_for_timeout(300)
    check('Gauntlet pause offers END RUN', 'END RUN' in pg.evaluate("()=>document.getElementById('pm_exit').textContent"))
    pg.click('#pm_exit'); pg.click('#pm_exit'); pg.wait_for_timeout(1500)
    r = pg.evaluate("()=>({html:document.getElementById('brief').textContent.replace(/\\s+/g,' ').slice(0,120),best:localStorage.getItem('gs_svbest')})")
    check('END RUN shows the debrief and saves the best score', 'RUN ENDED ON WAVE 1' in r['html'] and '1234' in (r['best'] or ''), r)
    pg.close()
    # --- skirmish + phone layout
    pg = R.page(1280, 720, '?sk=darter:1&q=low'); pg.wait_for_timeout(1500)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    check('skirmish pause offers EXIT SKIRMISH', 'EXIT SKIRMISH' in pg.evaluate("()=>document.getElementById('pm_exit').textContent")); pg.close()
    pg = R.page(844, 390, '?free&go&touch&q=low', touch=True); pg.wait_for_timeout(1500)
    pg.tap('#bpause'); pg.wait_for_timeout(400)
    r = pg.evaluate("()=>{const o=document.getElementById('pauseOv').getBoundingClientRect();return {paused:__game.userPause,fits:o.top>=0&&o.bottom<=innerHeight&&o.left>=0&&o.right<=innerWidth,h:Math.round(o.height)}}")
    check('touch: the II button opens the menu and it fits an 844x390 screen', r['paused'] and r['fits'], r)
    pg.screenshot(path='/tmp/gs_shots/pause_phone.png'); pg.close()
    check('no console errors', not R.errs, R.errs[:3])
print('PAUSE', 'OK' if ok else 'FAIL')

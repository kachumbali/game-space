#!/usr/bin/env python3
"""Build src/14_samples.js (small CC0 sound samples embedded as base64 mp3) from the source files listed in docs/AUDIO_CREDITS.md.
usage: gen_samples.py <dir with the downloaded sources>   (needs ffmpeg). Sources: see docs/AUDIO_CREDITS.md"""
import base64, subprocess, sys, os, json
src = sys.argv[1]
# name -> (file, ffmpeg filter/trim args)
S = {
  'expl1': ('spacesfx/SpaceSFX1/explosion1.ogg', []), 'expl2': ('spacesfx/SpaceSFX1/explosion3.ogg', []),
  'expl3': ('spacesfx/SpaceSFX1/explosion5.ogg', []), 'expl4': ('synexp.flac', ['-t', '1.2']),
  'pulse': ('spacesfx/SpaceSFX1/laser3.ogg', []), 'fang': ('spacesfx/SpaceSFX1/laser4.ogg', []),
  'warp': ('warp.wav', ['-t', '5', '-af', 'afade=t=out:st=4:d=1']),
}
out = {}
for k, (f, extra) in S.items():
    tmp = f'/tmp/_s_{k}.mp3'
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', os.path.join(src, f), *extra, '-ac', '1', '-ar', '32000', '-b:a', '48k', tmp], check=True)
    out[k] = 'data:audio/mpeg;base64,' + base64.b64encode(open(tmp, 'rb').read()).decode()
js = '// GENERATED by tools/gen_samples.py - CC0 samples, see docs/AUDIO_CREDITS.md. Do not edit by hand.\nconst SAMPLE_DATA = ' + json.dumps(out) + ';\n'
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', '14_samples.js'), 'w').write(js)
print({k: len(v) // 1024 for k, v in out.items()}, 'KB base64')
